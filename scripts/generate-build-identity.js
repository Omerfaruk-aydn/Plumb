// Generates packages/cli/src/generated/buildIdentity.ts — the embedded build
// identity consumed by `plumb --runtime-identity` and `plumb --diagnose-logo`.
//
// Contract:
//   - Repository builds (a .git directory is present) MUST resolve the full
//     Git HEAD; failure aborts the build with a non-zero exit code.
//   - Non-repository builds (source tarball) fall back to the GIT_COMMIT
//     environment variable and finally to 'unknown'.
//   - The linked global command compares the embedded HEAD against the live
//     repository HEAD and fails `--runtime-identity` when they differ.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptPath = fileURLToPath(import.meta.url);
const root = join(dirname(scriptPath), '..');
const relativeScriptPath = relative(root, scriptPath);
const generatedDir = join(root, 'packages', 'cli', 'src', 'generated');
const outputFile = join(generatedDir, 'buildIdentity.ts');
const cliPackageJsonPath = join(root, 'packages', 'cli', 'package.json');

function resolveGitHead() {
  const envCommit = process.env.GIT_COMMIT;
  if (envCommit && /^[0-9a-f]{40}$/i.test(envCommit.trim())) {
    return { head: envCommit.trim().toLowerCase(), source: 'GIT_COMMIT env' };
  }
  try {
    const head = execFileSync('git', ['rev-parse', 'HEAD'], {
      encoding: 'utf-8',
      cwd: root,
      stdio: ['ignore', 'pipe', 'pipe'],
    }).trim();
    if (/^[0-9a-f]{40}$/i.test(head)) {
      return { head: head.toLowerCase(), source: 'git rev-parse HEAD' };
    }
    return { head: null, source: 'git rev-parse HEAD (unparseable output)' };
  } catch (err) {
    return {
      head: null,
      source: `git rev-parse HEAD failed: ${err instanceof Error ? err.message : String(err)}`,
    };
  }
}

const isRepositoryBuild = existsSync(join(root, '.git'));
const { head, source } = resolveGitHead();

if (!head && isRepositoryBuild) {
  console.error(
    `[generate-build-identity] FATAL: repository build requires a resolvable Git HEAD.\n` +
      `  Resolution attempted via: ${source}\n` +
      `  Set the GIT_COMMIT environment variable to a full 40-char SHA to override.`,
  );
  process.exit(1);
}

const gitHead = head ?? 'unknown';
const packageVersion = JSON.parse(readFileSync(cliPackageJsonPath, 'utf-8'))
  .version;
const buildTimestamp = new Date().toISOString();

if (!existsSync(generatedDir)) {
  mkdirSync(generatedDir, { recursive: true });
}

const fileContent = `/**
 * @license
 * Copyright 2026 PLUMB Authors
 * SPDX-License-Identifier: Apache-2.0
 */

// This file is auto-generated by the build script (${relativeScriptPath})
// Do not edit this file manually. Regenerate via the CLI package build.
export interface PlumbBuildIdentity {
  /** Full 40-char Git HEAD baked in at build time ('unknown' for tarball builds). */
  readonly gitHead: string;
  /** Version of the plumb-cli package at build time. */
  readonly packageVersion: string;
  /** Absolute source root of the repository at build time. */
  readonly sourceRoot: string;
  /** ISO-8601 UTC timestamp of the build. */
  readonly buildTimestamp: string;
  /** CLI entry module (repository-relative). */
  readonly entryModule: string;
  /** PLUMB provider startup module (repository-relative source). */
  readonly providerStartupModule: string;
  /** PLUMB provider registry module (repository-relative source). */
  readonly providerRegistryModule: string;
  /** Animated wordmark component module (repository-relative source). */
  readonly wordmarkModule: string;
}

export const BUILD_IDENTITY: PlumbBuildIdentity = {
  gitHead: '${gitHead}',
  packageVersion: '${packageVersion}',
  sourceRoot: ${JSON.stringify(root)},
  buildTimestamp: '${buildTimestamp}',
  entryModule: 'packages/cli/dist/index.js',
  providerStartupModule: 'packages/core/src/config/plumbInit.ts',
  providerRegistryModule: 'packages/provider/src/registry/provider-registry.ts',
  wordmarkModule: 'packages/cli/src/ui/components/PlumbAnimatedWordmark.tsx',
} as const;
`;

writeFileSync(outputFile, fileContent);
console.log(
  `[generate-build-identity] Embedded HEAD ${gitHead} (${source}) into ${relative(root, outputFile)}`,
);
